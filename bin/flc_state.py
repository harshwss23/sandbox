import json
import os
import re
import subprocess
import sys
import uuid
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

BIN_DIR = Path(__file__).resolve().parent
FLC_HOME = Path(os.environ.get("FLC_HOME", BIN_DIR.parent))
DEFAULT_TASK = FLC_HOME / "task"

SCHEMA_VERSION = "1.1"

# The fields that never vary between tasks, gathered in one place so each has a
# single definition to read and to change.
AGENT_TIMEOUT_SEC = 10800.0
VERIFIER_TIMEOUT_BASE_SEC = 300.0
VERIFIER_TIMEOUT_PER_RUBRIC_SEC = 45.0
BUILD_TIMEOUT_SEC = 1800.0
CPUS = 4
MEMORY_MB = 16384
STORAGE_FLOOR_MB = 20480
GPUS = 0

# How much context the task itself has to put in front of the model, measured
# from the finished run as peak minus the harness baseline. The allowance is
# added back so the figure means the same thing across agents of different
# weights: a task reads as 32k whether the harness it ran under cost 5k or 27k.
CONTEXT_ADDED_FLOOR = 27_000
HARNESS_ALLOWANCE = 5_000

# The difficulty bar. A task the solver already passes measures nothing, so the
# run has to score below this to be deliverable.
MAX_SOLVER_REWARD = 0.50

# The floor on how many checks a task carries -- rubric criteria and unit tests
# together. A task measured by a handful of criteria records where the answer
# landed and not how it got there, and the route is where the interesting
# failures are. Enforced at /flc-grade and again at /flc-deliver.
MIN_CHECKS = 20

# How many hallucination criteria there are, and how many of them may describe a
# failure the run never committed. The two halves of one instruction.
#
# The floor is the count, and it is a property of the rubric, so /flc-rubrics
# enforces it: five hallucination criteria, counted over the negative lines
# under the heading rather than over the heading, so that it is the same set of
# criteria the count at /flc-grade reports on. A positive line under
# Non-hallucination is not one of them.
#
# The cap is the other half. Up to two of the five may be written in
# anticipation -- a wrong turn the material makes attractive that this model
# happened to avoid -- and a set where every one of them fired is better than
# one where two did not, since a failure nobody was seen to commit is by
# construction not one the setup compelled. There is no label for an
# anticipated criterion and there cannot usefully be one: it is only visible
# after grading, as a negative that did not fire, so the cap is reported at
# /flc-grade rather than enforced at /flc-rubrics.
HALLUCINATION_FLOOR = 5
ANTICIPATED_CAP = 2

# The pytest the unit tests run under, pinned like the base image so a rebuild
# months from now collects and reports the same way.
PYTEST_PIN = "pytest==8.4.2"

# What a unit test may be worth, and what it is worth when nobody has said.
# The same closed set the rubric criteria use.
TEST_WEIGHTS = (5, 3, 1)
DEFAULT_TEST_WEIGHT = 3

# How much of a rubric, by weight, may go ungraded because the judge's safety
# filter declined the criterion's wording. Below this the criteria are dropped
# from the bundle, so what ships is exactly what was graded; at or above it
# there is too little of the rubric left for the score to describe the task.
REFUSAL_COVERAGE_LIMIT = 0.10


def default_state(task_id: str) -> dict[str, Any]:
    """A new task's state, seeded from the domain profile.

    The profile's packages and blocked sites are copied into the state rather
    than kept beside it, so /flc-add-package and /flc-unblock-domain act on them
    exactly as they act on anything the contributor added. A task that genuinely
    needs a site the domain blocks by default can therefore just unblock it.
    """
    info = profile()
    return {
        "_comment": "Generated by the /flc-* commands. Do not edit by hand.",
        "task_id": task_id,
        "domain": info.get("domain", "generic"),
        "seed_version": info.get("seed_version"),
        "required_files": [],
        "distractor_files": [],
        "packages": [{"ecosystem": eco, "spec": spec}
                     for eco in ("pip", "apt", "r")
                     for spec in info.get(eco, [])],
        "blocked_domains": list(info.get("blocked_domains", [])),
        "unit_tests": "unwritten",
        # Two numbers, never one. material_estimate is guessed from file sizes
        # before the run and decides nothing; context_added is measured from the
        # finished trajectory and is what the floor is enforced against. Sharing
        # a name is how the guess came to be read as the measurement.
        "material_estimate": None,
        "context_added": None,
        "steps_done": [],
        "steps_failed": {},
        "overrides": {},
    }


def task_root(explicit: str | os.PathLike[str] | None = None) -> Path:
    if explicit:
        return Path(explicit).resolve()
    env = os.environ.get("FLC_TASK")
    return Path(env).resolve() if env else DEFAULT_TASK


def state_path(root: Path) -> Path:
    return root / ".flc" / "state.json"


def load(root: Path) -> dict[str, Any]:
    path = state_path(root)
    if not path.exists():
        raise SystemExit(
            f"no task state at {path}\n"
            f"This does not look like a task folder. Expected {root}."
        )
    return json.loads(path.read_text())


def save(root: Path, state: dict[str, Any]) -> None:
    path = state_path(root)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(state, indent=2) + "\n")


def issues_path(root: Path) -> Path:
    return root / ".flc" / "technical_issues.jsonl"


def record_issue(root: Path, kind: str, detail: str, command: str = "",
                 repair: dict | None = None) -> None:
    """Append one fault in the sandbox's own tooling to the task's issue log.

    The log travels with the task folder, so what went wrong reaches whoever
    maintains the sandbox without the contributor relaying it. Never raises: a
    log that cannot be written must not become a second fault. The same fault
    reported again by the same command is recorded once.
    """
    try:
        if any(e.get("kind") == kind and e.get("command") == command
               and e.get("detail") == detail[-4000:] and not repair
               for e in issues(root)):
            return
        entry = {"at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
                 "seed_version": profile().get("seed_version") or "unknown",
                 "kind": kind, "command": command, "detail": detail[-4000:]}
        if repair:
            entry["repair"] = repair
        path = issues_path(root)
        path.parent.mkdir(parents=True, exist_ok=True)
        with path.open("a", encoding="utf-8") as out:
            out.write(json.dumps(entry) + "\n")
    except Exception:
        pass


def issues(root: Path) -> list[dict]:
    """Every fault recorded for this task, oldest first."""
    try:
        lines = issues_path(root).read_text(encoding="utf-8").splitlines()
    except OSError:
        return []
    out = []
    for line in lines:
        try:
            entry = json.loads(line)
        except ValueError:
            continue
        if isinstance(entry, dict):
            out.append(entry)
    return out


def mark_done(root: Path, step: str) -> None:
    state = load(root)
    if step not in state["steps_done"]:
        state["steps_done"].append(step)
    state.get("steps_failed", {}).pop(step, None)
    save(root, state)


# steps_done records successes, so an attempt that failed is recorded here
# instead: "attempted and refused" is a different state from "never attempted".
MIN_OVERRIDE_REASON = 20


def mark_failed(root: Path, step: str, check: str, detail: str = "") -> None:
    state = load(root)
    state.setdefault("steps_failed", {})[step] = {
        "at": _now(),
        "check": check,
        "detail": detail,
    }
    save(root, state)


def record_override(root: Path, check: str, reason: str, step: str) -> None:
    """Record that a contributor went past a check, and why.

    Raises ValueError on a reason too short to be one. The written reason is
    the whole point: an override with no account of itself is indistinguishable
    from the check never having fired.
    """
    reason = reason.strip()
    if len(reason) < MIN_OVERRIDE_REASON:
        raise ValueError(
            f"an override needs a reason of at least {MIN_OVERRIDE_REASON} "
            f"characters saying why this is the right call; got {len(reason)}"
        )
    state = load(root)
    state.setdefault("overrides", {})[check] = {
        "at": _now(),
        "reason": reason,
        "step": step,
    }
    save(root, state)


def overridden(state: dict[str, Any], check: str) -> dict | None:
    return (state.get("overrides") or {}).get(check)


def _now() -> str:
    from datetime import datetime, timezone
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


