#!/usr/bin/env python3
"""Read and write a task's generated state, and regenerate what depends on it.

Imported by every other script in bin/. Nothing here is written by hand: the
contributor's four files are workspace/, prompt.md, tests/rubrics.md and
tests/verifier.py, and this module owns everything else.

Run directly to inspect or set a value:

    python3 flc_state.py                     # print the state
    python3 flc_state.py get unit_tests
    python3 flc_state.py set unit_tests skipped
    python3 flc_state.py mark grade         # record a step as done
    python3 flc_state.py failed grade context_floor "23,100 tokens"
    python3 flc_state.py override context_floor rubrics "the reason, in full"
    python3 flc_state.py fingerprint run_fingerprint   # what this run is against
    python3 flc_state.py record-run JOB MODEL AGENT    # what this run was started with,
                                                       # and against which answer
    python3 flc_state.py check-resources    # can this machine run the task
"""

from __future__ import annotations

