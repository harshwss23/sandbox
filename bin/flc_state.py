def run_state(root: Path) -> str:
    """Where the solver run is: "none", "running", or "finished".

    This is what makes the two-phase rubric step possible. Completion criteria
    come from the ground truth and can be written while the run is going;
    non-hallucination criteria cannot be written until there is an answer to
    read, so the gate on them has to know which of those two moments this is.

    Liveness is a signal to the pid run_solver.sh recorded. A pid that is gone
    means the run is over -- successfully or not, which is a distinction for the
    grading step and not for this one.

    Over is not the same as having produced anything, though, and "finished"
    means a transcript landed. A run that never reached the model leaves
    "none", the same as one that was never started: for the only caller that
    gates on the phase, both mean there is no answer to write the
    non-hallucination criteria from. run_attempted tells them apart for the
    callers that report rather than gate.
    """
    try:
        state = load(root)
    except SystemExit:
        return "none"
    pid = state.get("run_pid")
    if pid not in (None, "", 0):
        try:
            os.kill(int(pid), 0)
            return "running"
        except PermissionError:
            return "running"          # alive, just not ours to signal
        except (ProcessLookupError, OSError, ValueError, TypeError):
            pass
    return "finished" if run_transcript(root) else "none"


def run_transcript(root: Path) -> Path | None:
    """The transcript the recorded run produced, if it produced one.

    run_solver.sh creates the job directory before starting Harbor, so the
    directory existing says only that a run was attempted. A container Harbor
    could not start leaves the directory behind and still exits 0, which read
    as a finished run everywhere that asked.

    Globbed rather than resolved through the job layout, which has two shapes;
    solver_answer.find_trajectory does the same thing for the same reason and
    cannot be imported here, since it imports this module.

    Only whether this found one is used. Which one it names is not an answer to
    "which attempt is the run" -- `solver_answer.resolve_trial()` is the single
    place that decides that, and reading a transcript chosen here instead would
    put this module's ordering beside that one's.
    """
    try:
        job = load(root).get("last_job")
    except SystemExit:
        return None
    if not job or not Path(job).exists():
        return None
    found = sorted(Path(job).rglob("*trajectory*.json"))
    return found[-1] if found else None


def run_attempted(root: Path) -> bool:
    """Whether a run was started, whatever came of it.

    The counterpart to run_state's "none": together they tell a run that never
    happened from one that happened and produced nothing.
    """
    try:
        job = load(root).get("last_job")
    except SystemExit:
        return False
    return bool(job) and Path(job).exists()


# --- generated files ---------------------------------------------------------

def profile() -> dict:
    """This seeded directory's domain profile.

    Written by bin/make_seed.py when the tree was generated. Working directly in
    the source tree there is none, so fall back to plain Python: enough to build
    and run a task, just without the domain's usual packages.
    """
    path = BIN_DIR / "profile.json"
    if path.exists():
        return json.loads(path.read_text())
    return {
        "domain": "generic",
        "label": "Generic",
        "base_image": "python:3.12-slim-bookworm",
        "base_image_ref": "python:3.12-slim-bookworm",
    }


def base_image() -> str:
    return profile()["base_image"]


def _dir_size_mb(path: Path) -> int:
    if not path.exists():
        return 0
    total = 0
    for p in path.rglob("*"):
        if p.is_file() and not p.is_symlink():
            try:
                total += p.stat().st_size
            except OSError:
                pass
    return total // (1024 * 1024)


_TOML_INT_RE = "^{key} *= *([0-9]+) *$"


def _declared(root: Path, key: str) -> int | None:
    """What the generated task.toml asks the harness for.

    Read back out of the file rather than off the constant, because the file
    is what Harbor reads. Matched with a regex rather than parsed: this module
    writes the line itself, and tomllib is not on every Python a VM may carry.
    """
    path = root / "task.toml"
    if not path.exists():
        return None
    found = re.search(_TOML_INT_RE.format(key=key), path.read_text(),
                      re.MULTILINE)
    return int(found.group(1)) if found else None


def _physical_memory_mb() -> int | None:
    try:
        with open("/proc/meminfo") as handle:
            for line in handle:
                if line.startswith("MemTotal:"):
                    return int(line.split()[1]) // 1024
    except (OSError, ValueError, IndexError):
        pass
    return None


def resource_check(root: Path) -> dict:
    """Whether this machine can satisfy what task.toml asks for.

    Docker refuses a container asking for more CPUs than the host has, and it
    refuses it after the image has been built. Harbor reports that as an
    exception inside a run that still exits 0, so the cost of finding out late
    is a whole run.

    Memory is a note rather than a refusal because Docker permits a limit above
    physical memory and the container starts anyway. Anything unmeasurable is
    reported as such and blocks nothing.
    """
    cpus, memory = _declared(root, "cpus"), _declared(root, "memory_mb")
    have_cpus, have_memory = os.cpu_count(), _physical_memory_mb()
    out: dict[str, Any] = {"cpus": cpus, "cpus_available": have_cpus,
                           "memory_mb": memory,
                           "memory_mb_available": have_memory,
                           "ok": True, "why": "", "notes": []}
    if cpus is None or have_cpus is None:
        out["why"] = ("could not tell what this task asks for or what this "
                      "machine has, so nothing was checked")
        return out
    if cpus > have_cpus:
        out["ok"] = False
        out["why"] = (f"task.toml asks for {cpus} CPUs and this machine has "
                      f"{have_cpus}")
    if memory and have_memory and memory > have_memory:
        out["notes"].append(
            f"task.toml asks for {memory} MB of memory and this machine has "
            f"{have_memory} MB. Docker allows this and the container will "
            f"start, but a run that dies early is worth suspecting here first.")
    return out


def _rubric_count(root: Path) -> int:
    path = root / "tests" / "rubrics.json"
    if not path.exists():
        return 0
    try:
        return len(json.loads(path.read_text()))
    except Exception:
        return 0


def _test_count(root: Path) -> int:
    """How many unit tests the task carries.

    Read off the compiled weights rather than the suite, which is the same
    file the grader multiplies by and so cannot disagree with the score. A
    tree with no unit-test path never writes it, and a suite set aside by
    /flc-skip-tests is not counted, which is correct both times: neither
    scores anything.
    """
    if not (root / "tests" / "verifier.py").exists():
        return 0
    path = root / "tests" / "test_weights.json"
    if not path.exists():
        return 0
    try:
        weights = json.loads(path.read_text()).get("weights")
        return len(weights) if isinstance(weights, dict) else 0
    except Exception:
        return 0


def check_count(root: Path) -> dict:
    """The criteria and the unit tests, which are counted together.

    One task is measured by one instrument, so which half a check sits in is
    not the contributor's problem to balance -- a rubrics-only domain reaches
    the floor on criteria alone, and one with a suite splits it however the
    task falls out.
    """
    rubrics, tests = _rubric_count(root), _test_count(root)
    return {"rubrics": rubrics, "tests": tests, "total": rubrics + tests,
            "floor": MIN_CHECKS, "enough": rubrics + tests >= MIN_CHECKS}


def write_dockerfile(root: Path) -> Path:
    """The task's environment/Dockerfile, built on the domain's base image.

    The image is pinned by digest so a rebuild months from now is the same
    image, and the install helpers are copied in rather than assumed present:
    the base is a public image nobody here controls, and a task that only builds
    against a base we maintain is not reproducible anywhere else.

    packages.txt and blocked_domains.txt are named unconditionally -- both
    helpers exit cleanly on an empty file, and a Dockerfile whose shape depends
    on the contributor's choices is one more thing that can be wrong.

    pytest is installed only where tests/run_verifier.py exists, and separately
    from packages.txt: that file is the contributor's own list and
    /flc-add-package can remove from it.
    """
    info = profile()
    path = root / "environment" / "Dockerfile"
    path.parent.mkdir(parents=True, exist_ok=True)
    pytest_step = ""
    if (root / "tests" / "run_verifier.py").exists():
        pytest_step = (
            "# The test runner, installed separately from packages.txt.\n"
            f"RUN pip3 install --no-cache-dir {PYTEST_PIN} \\\n"
            f" || pip3 install --no-cache-dir --break-system-packages {PYTEST_PIN}\n"
            "\n"
        )
    path.write_text(
        "# Generated file. Edits are overwritten: the inputs are packages.txt\n"
        "# and blocked_domains.txt.\n"
        f"# Domain profile: {info.get('label', 'Generic')}\n"
        f"FROM {info['base_image']}\n"
        "\n"
        "COPY .flc/flc-install-packages .flc/flc-block-domains /usr/local/bin/\n"
        "RUN chmod +x /usr/local/bin/flc-install-packages "
        "/usr/local/bin/flc-block-domains\n"
        "\n"
        + pytest_step +
        "COPY .flc/packages.txt /tmp/flc-packages.txt\n"
        "RUN flc-install-packages /tmp/flc-packages.txt\n"
        "\n"
        "COPY .flc/blocked_domains.txt /tmp/flc-blocked-domains.txt\n"
        "RUN flc-block-domains /tmp/flc-blocked-domains.txt\n"
        "\n"
        "COPY workspace/ /workspace/\n"
        "WORKDIR /workspace\n"
    )
    return path


def write_task_toml(root: Path) -> Path:
    """The Harbor manifest. Constants plus values measured off the task itself.

    Kept in the same shape as the reference SWE-Atlas task: no project-specific
    fields, nothing in [metadata] that a runtime consumes.
    """
    state = load(root)
    workspace_mb = _dir_size_mb(root / "environment" / "workspace")
    # Headroom for the image layers, the agent's own output, and the copy the
    # verifier takes. A dataset that fills the disk mid-run is scored as a
    # failure, and looks exactly like a model that gave up.
    storage_mb = max(STORAGE_FLOOR_MB, workspace_mb * 4 + 10240)
    verifier_sec = VERIFIER_TIMEOUT_BASE_SEC + VERIFIER_TIMEOUT_PER_RUBRIC_SEC * _rubric_count(root)

    path = root / "task.toml"
    path.write_text(
        f'schema_version = "{SCHEMA_VERSION}"\n'
        "\n"
        "[task]\n"
        f'name = "{state["task_id"]}"\n'
        'description = ""\n'
        "authors = []\n"
        "keywords = []\n"
        "\n"
        "[metadata]\n"
        "\n"
        "[verifier]\n"
        f"timeout_sec = {verifier_sec:.1f}\n"
        "\n"
        "[agent]\n"
        f"timeout_sec = {AGENT_TIMEOUT_SEC:.1f}\n"
        "\n"
        "[environment]\n"
        f"build_timeout_sec = {BUILD_TIMEOUT_SEC:.1f}\n"
        f"cpus = {CPUS}\n"
        f"memory_mb = {MEMORY_MB}\n"
        f"storage_mb = {storage_mb}\n"
        f"gpus = {GPUS}\n"
        "allow_internet = true\n"
        "mcp_servers = []\n"
        "\n"
        "[verifier.env]\n"
        'EVAL_API_KEY = "${OPENAI_API_KEY}"\n'
        'EVAL_BASE_URL = "${OPENAI_API_BASE}"\n'
        'EVAL_MODEL = "${EVAL_MODEL:-anthropic/claude-opus-4-5-20251101}"\n'
        # Set only by run_solver.sh, so an authoring run does not grade against
        # criteria that are half written. test.sh defers on the exact string 1
        # and grades on anything else, including this line unexpanded, so a
        # delivered run is unaffected either way.
        'FLC_DEFER_GRADING = "${FLC_DEFER_GRADING:-0}"\n'
        # The other half of that pair, generated rather than patched in:
        # `run_solver.sh` regenerates this file on the way past. Both default
        # to 0, which is "grade".
        'FLC_GRADE_NOW = "${FLC_GRADE_NOW:-0}"\n'
        "\n"
        "[environment.env]\n"
        "\n"
        "[solution.env]\n"
    )
    return path


def _strip_html_comments(text: str) -> str:
    return re.sub(r"<!--.*?-->", "", text, flags=re.DOTALL)


def contributor_prompt(root: Path) -> str:
    """The contributor's prompt text, with the template's guidance removed."""
    path = root / "prompt.md"
    if not path.exists():
        return ""
    return _strip_html_comments(path.read_text()).strip()


def write_instruction(root: Path) -> Path:
    """instruction.md: the contributor's prompt, and nothing else.

    This file ships in the bundle and is what the agent is re-run against, so
    it carries no scaffolding of ours -- no framing, no house style,
    and no instruction about where to put an answer. The agent's final message
    is the answer, read from the transcript, which removes the one way a good
    run could score zero by ignoring a protocol.

    Generated rather than authored only so it always matches prompt.md.
    """
    body = contributor_prompt(root)
    path = root / "instruction.md"
    path.write_text(body + "\n")
    # The judge scores against the same text.
    tests = root / "tests"
    tests.mkdir(parents=True, exist_ok=True)
    (tests / "prompt.txt").write_text(body + "\n")
    return path


def write_inputs_manifest(root: Path) -> Path:
    """Fingerprint the uploaded inputs, so the judge can tell them from outputs.

    The verifier sees one /workspace: the model's, after the run. Without a
    record of what was there beforehand it cannot distinguish a file the model
    produced from one it was given, and "did it write the results file" becomes
    unanswerable.
    """
    workspace = root / "environment" / "workspace"
    manifest = {}
    for rel in workspace_files(root):
        path = workspace / rel
        try:
            manifest[rel] = hashlib.sha256(path.read_bytes()).hexdigest()
        except OSError:
            manifest[rel] = ""
    tests = root / "tests"
    tests.mkdir(parents=True, exist_ok=True)
    path = tests / "inputs_manifest.json"
    path.write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n")
    return path


def write_packages(root: Path) -> Path:
    """environment/.flc/packages.txt, from the state's package list."""
    state = load(root)
    lines = ["# Extra packages for this task, one per line, prefixed with pip,",
             "# apt or r.", ""]
    for entry in state.get("packages", []):
        lines.append(f"{entry['ecosystem']} {entry['spec']}")
    path = root / "environment" / ".flc" / "packages.txt"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines).rstrip() + "\n")
    return path


def write_blocked_domains(root: Path) -> Path:
    """environment/.flc/blocked_domains.txt, from the state's block list."""
    state = load(root)
    lines = ["# Sites the solver must not reach.", ""]
    lines += state.get("blocked_domains", [])
    path = root / "environment" / ".flc" / "blocked_domains.txt"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines).rstrip() + "\n")
    return path


def regenerate(root: Path) -> None:
    """Rewrite every generated file from the current state."""
    write_packages(root)
    write_blocked_domains(root)
    write_dockerfile(root)
    write_instruction(root)
    write_inputs_manifest(root)
    write_task_toml(root)


# --- what a score is a score of ----------------------------------------------
#
# The digests below record what a score was measured against: `run_solver.sh`
# records what the model saw, `run_grader.py` records what the judge was given,
# and `/flc-deliver` compares both against the files on disk instead of grading
# a second time.
#
# Generated files rather than sources. Those are what reach the model and the
# judge, and they are stable under an unrelated regenerate(), which rewrites
# them byte for byte from unchanged inputs.
GRADE_INPUTS = {
    "prompt": "instruction.md",
    "workspace": "tests/inputs_manifest.json",
    "rubrics": "tests/rubrics.json",
    # Scored like a criterion, so it pins like one. A task with no suite
    # records an empty digest, and an absent file compares equal to an absent
    # file below.
    "unit_tests": "tests/verifier.py",
    # What each of those tests is worth. Changing a weight changes the score
    # without changing a line of the suite, so it pins alongside it.
    "test_weights": "tests/test_weights.json",
}

# Which of them each piece of evidence rests on. A rubric that moved after the
# run is ordinary -- the non-hallucination criteria are written from the run --
# so the run is only about the prompt and the material.
RUN_INPUTS = ("prompt", "workspace")
GRADE_ONLY_INPUTS = ("rubrics", "unit_tests", "test_weights")


# The task's fixed point. Written before the model runs and not allowed to
# move afterwards, so it is pinned at the moment the run starts rather than
# folded into GRADE_INPUTS: nothing about it is regenerated, and a change to
# it invalidates no evidence -- it changes what the evidence was ever for.
GROUND_TRUTH = "solution/ground_truth.md"

# Why that answer is the only one an expert could reach. Written in the same
# sitting and kept beside it rather than inside it, because the two are read by
# different people for different reasons: the ground truth is what the criteria
# are held to, and this is what a reviewer reads to decide the task is
# gradeable at all.
JUSTIFICATION = "solution/underspecification_justification.md"
# The name a task scaffolded before v37 carries.
LEGACY_JUSTIFICATION = "solution/underspecification.md"


def justification_file(root: Path) -> Path:
    """The task's justification, under whichever name it was scaffolded with.

    The current name when neither exists, so a report of a missing file names
    the one to write.
    """
    current = root / JUSTIFICATION
    legacy = root / LEGACY_JUSTIFICATION
    if current.exists() or not legacy.exists():
        return current
    return legacy


def ground_truth_digest(root: Path) -> str:
    return sha256_file(root / GROUND_TRUTH)


# Heading words, tried in this order. "What the model cannot know" has to be
# tried before the distractor words, and the derivation words before "answer",
# since "How the answer is derived" carries both.
_UNKNOWABLE_WORDS = ("cannot know", "cannot be known")
_DISTRACTOR_WORDS = ("mislead", "trap", "distract", "wrong")
_DERIVATION_WORDS = ("deriv", "evidence", "method", "how it", "how the")


def ground_truth_sections(root: Path) -> dict[str, str]:
    """The ground truth split by what each section is for.

    Matched on words rather than exact headings, so the template's headings and
    a contributor's own wording both work. Keys: "answer", "derivation",
    "distractors", "unknowable", "preamble", and any other heading lowercased.
    Text is as written, template comments included.
    """
    try:
        text = (root / GROUND_TRUTH).read_text(errors="replace")
    except OSError:
        return {}
    sections: dict[str, str] = {}
    current = "preamble"
    buffer: list[str] = []
    for line in text.splitlines():
        heading = re.match(r"^#{1,4}\s+(.*)", line)
        if heading:
            sections[current] = sections.get(current, "") + "\n".join(buffer)
            buffer = []
            title = heading.group(1).lower()
            if any(w in title for w in _UNKNOWABLE_WORDS):
                current = "unknowable"
            elif any(w in title for w in _DISTRACTOR_WORDS):
                current = "distractors"
            elif any(w in title for w in _DERIVATION_WORDS):
                current = "derivation"
            elif "answer" in title:
                current = "answer"
            else:
                current = title
            continue
        buffer.append(line)
    sections[current] = sections.get(current, "") + "\n".join(buffer)
    return sections


# What is sealed before a run: the answer, how it is reached, and -- where the
# task has one -- what the model cannot know. The distractor notes and the
# justification can be finished after a run without anything recording it.
SEALED_SECTIONS = ("answer", "derivation", "unknowable")
SEALED_REQUIRED = ("answer", "derivation")


def sealed_sections(root: Path) -> dict[str, str]:
    """The sealed sections as written, comments removed, empty ones left out."""
    found = ground_truth_sections(root)
    out = {}
    for key in SEALED_SECTIONS:
        body = _strip_html_comments(found.get(key, "")).strip()
        if body:
            out[key] = body
    return out


def sealed_digest(sections: dict[str, str]) -> str:
    return hashlib.sha256(json.dumps(sections, sort_keys=True)
                          .encode("utf-8")).hexdigest()


def environment_digest(state: dict[str, Any]) -> str:
    """The packages and the block list the image is built with."""
    packages = sorted(f"{p.get('ecosystem')} {p.get('spec')}"
                      for p in state.get("packages") or [] if isinstance(p, dict))
    blocked = sorted(str(d) for d in state.get("blocked_domains") or [])
    return hashlib.sha256(json.dumps({"packages": packages, "blocked": blocked})
                          .encode("utf-8")).hexdigest()


def run_inputs(root: Path) -> dict[str, Any]:
    """What a run is about to be started against, as run_solver.sh records it.

    Kept per run and never overwritten, so the answer as it stood before each
    run can be read back after any number of later ones.
    """
    sealed = sealed_sections(root)
    return {"prompt": contributor_prompt(root),
            "workspace_sha256": sha256_file(root / GRADE_INPUTS["workspace"]),
            "environment_sha256": environment_digest(load(root)),
            "sealed": sealed,
            "sealed_sha256": sealed_digest(sealed),
            "ground_truth_sha256": ground_truth_digest(root)}


def run_record(state: dict[str, Any], job: str | os.PathLike[str] | None) -> dict:
    """The per-run record for a job, by its directory name; {} if there is none."""
    if not job:
        return {}
    runs = state.get("runs")
    entry = runs.get(Path(job).name) if isinstance(runs, dict) else None
    return entry if isinstance(entry, dict) else {}


def justification_digest(root: Path) -> str:
    return sha256_file(justification_file(root))


def authoring_sources(root: Path) -> dict[str, Path]:
    """What delivery copies into delivery/authoring/, by the name each is copied as.

    The task state is copied there too and is not listed: it goes on being
    written after delivery, so its copy records that moment.
    """
    return {"prompt.md": root / "prompt.md",
            "rubrics.md": root / "tests" / "rubrics.md",
            "test_weights.md": root / "tests" / "test_weights.md",
            "ground_truth.md": root / GROUND_TRUTH,
            Path(JUSTIFICATION).name: justification_file(root),
            "labels.md": root / "solution" / "labels.md"}


def sha256_file(path: Path) -> str:
    """The file's digest, or "" if there is nothing to read."""
    try:
        return hashlib.sha256(path.read_bytes()).hexdigest()
    except OSError:
        return ""


def fingerprint(root: Path) -> dict[str, str]:
    return {name: sha256_file(root / rel) for name, rel in GRADE_INPUTS.items()}


def fingerprint_drift(recorded: Any, current: dict[str, str],
                      keys: tuple[str, ...]) -> list[str]:
    """Which of `keys` has moved since `recorded` was taken.

    A key that was never recorded counts as moved: "nothing was written down"
    is not evidence that nothing changed, and the alternative is that deleting
    a line of state buys a pass. A key recorded as "" is a different thing --
    the file was not there when the evidence was made -- and still being absent
    is not a change.
    """
    if not isinstance(recorded, dict):
        return list(keys)
    return [k for k in keys
            if k not in recorded or recorded[k] != current.get(k)]


# The file a contributor would go and change, which is not the one fingerprinted:
# instruction.md and rubrics.json are generated from prompt.md and rubrics.md,
# and the manifest from the workspace. Naming the generated file sends them to
# one they are told never to edit.
DRIFT_NAMES = {
    "prompt": "prompt.md",
    "workspace": "environment/workspace/",
    "rubrics": "tests/rubrics.md",
    "unit_tests": "tests/verifier.py",
    "test_weights": "tests/test_weights.md",
}


def drift_names(root: Path, moved: list[str]) -> list[str]:
    """Name the moved keys, leaving out any file this task cannot have.

    `unit_tests` is in GRADE_INPUTS in both trees so the fingerprint has one
    shape everywhere, but the rubrics-only tree has no verifier at all and a
    task that ran /flc-skip-tests has renamed its own. A key can still be
    reported as moved there -- an older delivery record never wrote it down,
    and unrecorded counts as moved -- and naming it then sends a contributor
    looking for a file that is not on their disk, which is the shape of remedy
    this project has already shipped once and had to fix.
    """
    named = []
    for key in moved:
        name = DRIFT_NAMES.get(key, key)
        target = GRADE_INPUTS.get(key)
        if target and not (root / target).exists() and not (root / name).exists():
            continue
        named.append(name)
    return named


# --- helpers other scripts share ---------------------------------------------

def workspace_files(root: Path) -> list[str]:
    """Every file the model will see, as workspace-relative paths."""
    base = root / "environment" / "workspace"
    if not base.exists():
        return []
    out = []
    for p in sorted(base.rglob("*")):
        if p.is_file() and not p.is_symlink() and p.name != "PUT_YOUR_FILES_HERE.txt":
            out.append(str(p.relative_to(base)))
    return out


def git(root: Path, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run(["git", "-C", str(root), *args],
                          capture_output=True, text=True, check=False)


def _cli() -> int:
    root = task_root()
    args = sys.argv[1:]
    if not args:
        print(json.dumps(load(root), indent=2))
        return 0
    if args[0] == "get" and len(args) == 2:
        print(json.dumps(load(root).get(args[1])))
        return 0
    if args[0] == "set" and len(args) >= 3:
        state = load(root)
        raw = " ".join(args[2:])
        try:
            state[args[1]] = json.loads(raw)
        except json.JSONDecodeError:
            state[args[1]] = raw
        save(root, state)
        return 0
    if args[0] == "mark" and len(args) == 2:
        mark_done(root, args[1])
        return 0
    if args[0] == "failed" and len(args) >= 3:
        mark_failed(root, args[1], args[2], " ".join(args[3:]))
        return 0
    if args[0] == "override" and len(args) >= 4:
        try:
            record_override(root, args[1], " ".join(args[3:]), args[2])
        except ValueError as exc:
            print(str(exc), file=sys.stderr)
            return 2
        return 0
    if args[0] == "record-run" and len(args) == 4:
        inputs = run_inputs(root)
        state = load(root)
        runs = state.get("runs") if isinstance(state.get("runs"), dict) else {}
        name = Path(args[1]).name
        entry = runs.get(name)
        entry = entry if isinstance(entry, dict) else {}
        entry.update({"model": args[2], "agent": args[3], "started": _now(),
                      **inputs})
        # What run_guard.py was told before this run: a confirmed rerun or a
        # reason for going past the limit. Kept only for the run it was for.
        pending = state.pop("run_guard_pending", None)
        if isinstance(pending, dict) and pending.get("job") == name:
            entry.update({k: v for k, v in pending.items() if k != "job"})
        runs[name] = entry
        state["runs"] = runs
        save(root, state)
        return 0
    if args[0] == "pin-ground-truth":
        state = load(root)
        state["ground_truth_sha256"] = ground_truth_digest(root)
        save(root, state)
        return 0
    if args[0] == "fingerprint" and len(args) == 2:
        state = load(root)
        state[args[1]] = fingerprint(root)
        save(root, state)
        return 0
    if args[0] == "regenerate":
        regenerate(root)
        return 0
    if args[0] == "check-resources":
        found = resource_check(root)
        for note in found["notes"]:
            print(f"  note: {note}")
        if found["ok"]:
            if found["why"]:
                print(f"  {found['why']}.")
            return 0
        seed = profile().get("seed_version") or "unknown"
        record_issue(root, "resource_check",
                     f"{found['why']}; seed {seed}, "
                     f"{found['cpus_available']} CPUs available", "run_solver.sh")
        print(
            f"\n  There's a technical issue on our side with this sandbox, not a\n"
            f"  problem with your task, and nothing you have written is affected.\n"
            f"  Please reach out to the project team.\n\n"
            f"  (For them: {found['why']}; seed {seed}.)\n",
            file=sys.stderr)
        return 2
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(_cli())
